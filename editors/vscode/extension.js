// LiteScript extension: the language server and the debug adapter are given by litescript-pg
// ("litescript-pg --lsp" and "litescript-pg --dap")

const vscode = require('vscode');
const childProcess = require('child_process');
const { LanguageClient, RevealOutputChannelOn } = require('vscode-languageclient/node');

let client = null;
let output = null;

// The path of litescript-pg (setting or PATH)
function playgroundPath() {
    const path = vscode.workspace.getConfiguration('litescript').get('playgroundPath');
    return path && path.trim() ? path.trim() : 'litescript-pg';
}

// Show an error about litescript-pg with a button to change the setting
function reportMissingPlayground(error) {
    const configure = 'Configure the path';
    vscode.window.showErrorMessage(
        `LiteScript: litescript-pg can't be started (${error}). Install it in the PATH or set "litescript.playgroundPath".`,
        configure
    ).then(choice => {
        if (choice === configure)
            vscode.commands.executeCommand('workbench.action.openSettings', 'litescript.playgroundPath');
    });
}

async function startClient() {
    const config = vscode.workspace.getConfiguration('litescript');
    const command = playgroundPath();
    const serverOptions = { command, args: ['--lsp'] };
    const clientOptions = {
        documentSelector: [
            { scheme: 'file', language: 'litescript' },
            { scheme: 'untitled', language: 'litescript' }
        ],
        synchronize: { configurationSection: 'litescript' },
        initializationOptions: { unknownVariables: config.get('diagnostics.unknownVariables') },
        outputChannel: output,
        revealOutputChannelOn: RevealOutputChannelOn.Never
    };
    client = new LanguageClient('litescript', 'LiteScript Language Server', serverOptions, clientOptions);
    try {
        await client.start();
    }
    catch (error) {
        client = null;
        reportMissingPlayground(error.message || error);
    }
}

async function stopClient() {
    if (client) {
        const old = client;
        client = null;
        try {
            await old.stop();
        }
        catch (error) {
            // The server is already stopped
        }
    }
}

// The LiteScript file of the active editor (saved first)
async function activeScript() {
    const editor = vscode.window.activeTextEditor;
    if (!editor || editor.document.languageId !== 'litescript') {
        vscode.window.showWarningMessage('LiteScript: open a .lsc file first.');
        return null;
    }
    if (editor.document.isUntitled) {
        vscode.window.showWarningMessage('LiteScript: save the file first.');
        return null;
    }
    if (editor.document.isDirty)
        await editor.document.save();
    return editor.document;
}

function quote(arg) {
    return /^[\w\-.\/\\:]+$/.test(arg) ? arg : `"${arg.replace(/"/g, '\\"')}"`;
}

// Run the current file in a terminal
async function runFile() {
    const document = await activeScript();
    if (!document)
        return;
    let terminal = vscode.window.terminals.find(t => t.name === 'LiteScript');
    if (!terminal)
        terminal = vscode.window.createTerminal('LiteScript');
    terminal.show(true);
    const command = quote(playgroundPath()) + ' ' + quote(document.fileName);
    // PowerShell needs the call operator to execute a quoted path
    const shell = (vscode.env.shell || '').toLowerCase();
    terminal.sendText((shell.includes('pwsh') || shell.includes('powershell')) && command.startsWith('"') ? '& ' + command : command);
}

// Debug the current file without launch.json
async function debugFile() {
    const document = await activeScript();
    if (!document)
        return;
    const folder = vscode.workspace.getWorkspaceFolder(document.uri);
    vscode.debug.startDebugging(folder, {
        type: 'litescript',
        request: 'launch',
        name: 'Debug ' + vscode.workspace.asRelativePath(document.uri),
        program: document.fileName,
        cwd: folder ? folder.uri.fsPath : undefined
    });
}

// Show the instructions generated by the compiler
async function disassemble() {
    const document = await activeScript();
    if (!document)
        return;
    childProcess.execFile(playgroundPath(), ['--disassemble', document.fileName], { maxBuffer: 64 * 1024 * 1024 }, async (error, stdout, stderr) => {
        if (error && !stdout) {
            if (error.code === 'ENOENT')
                reportMissingPlayground(error.message);
            else
                vscode.window.showErrorMessage('LiteScript: ' + (stderr || error.message).trim());
            return;
        }
        const assembly = await vscode.workspace.openTextDocument({ language: 'litescript-assembly', content: stdout });
        vscode.window.showTextDocument(assembly, { viewColumn: vscode.ViewColumn.Beside, preview: true });
    });
}

// Debug configurations: F5 without launch.json debugs the current file
class DebugConfigurationProvider {
    resolveDebugConfiguration(folder, config) {
        if (!config.type && !config.request && !config.name) {
            const editor = vscode.window.activeTextEditor;
            if (editor && editor.document.languageId === 'litescript') {
                config.type = 'litescript';
                config.request = 'launch';
                config.name = 'Debug the current file';
                config.program = '${file}';
            }
        }
        if (!config.program) {
            vscode.window.showErrorMessage('LiteScript: the debug configuration needs a "program".');
            return undefined;
        }
        if (!config.cwd && folder)
            config.cwd = folder.uri.fsPath;
        return config;
    }
}

class DebugAdapterFactory {
    createDebugAdapterDescriptor() {
        return new vscode.DebugAdapterExecutable(playgroundPath(), ['--dap']);
    }
}

// Tasks of type "litescript": { "type": "litescript", "files": ["tests/**/*.lsc"] }
class TaskProvider {
    provideTasks() {
        return [];
    }
    resolveTask(task) {
        const definition = task.definition;
        if (!Array.isArray(definition.files))
            return undefined;
        const args = [...(definition.options || []), ...definition.files];
        if (definition.args && definition.args.length > 0)
            args.push('--', ...definition.args);
        return new vscode.Task(definition, task.scope || vscode.TaskScope.Workspace, task.name || 'run', 'litescript',
            new vscode.ProcessExecution(playgroundPath(), args), ['$litescript']);
    }
}

async function activate(context) {
    output = vscode.window.createOutputChannel('LiteScript');
    context.subscriptions.push(output);
    context.subscriptions.push(
        vscode.commands.registerCommand('litescript.run', runFile),
        vscode.commands.registerCommand('litescript.debug', debugFile),
        vscode.commands.registerCommand('litescript.disassemble', disassemble),
        vscode.commands.registerCommand('litescript.restartServer', async () => {
            await stopClient();
            await startClient();
        }),
        vscode.debug.registerDebugConfigurationProvider('litescript', new DebugConfigurationProvider()),
        vscode.debug.registerDebugAdapterDescriptorFactory('litescript', new DebugAdapterFactory()),
        vscode.tasks.registerTaskProvider('litescript', new TaskProvider()),
        vscode.workspace.onDidChangeConfiguration(async event => {
            if (event.affectsConfiguration('litescript.playgroundPath')) {
                await stopClient();
                await startClient();
            }
        })
    );
    await startClient();
}

async function deactivate() {
    await stopClient();
}

module.exports = { activate, deactivate };
